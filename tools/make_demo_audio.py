"""Synthesise original demo sound effects and a background-music loop (no samples, no third-party audio).

Everything written here is generated by this script and released with open-explainer under the MIT License,
so the demo projects and tests have audio with clear redistribution rights.

usage: python tools/make_demo_audio.py <out_dir>
    <out_dir>/sfx/*.wav      whoosh-soft, whoosh-fast, pop-soft, pop-bright, click-ui, impact-low, ding-success, riser
    <out_dir>/music/calm-loop.wav   16 s, 90 BPM, loops seamlessly
"""
import sys
import wave
from pathlib import Path

import numpy as np

SR = 48000
rng = np.random.default_rng(42)


def write(path: Path, x: np.ndarray, stereo=True):
    path.parent.mkdir(parents=True, exist_ok=True)
    x = np.clip(x, -1, 1)
    if stereo and x.ndim == 1:
        x = np.stack([x, x], 1)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2 if stereo else 1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((x * 32767).astype("<i2").tobytes())


def t(d):
    return np.arange(int(d * SR)) / SR


def env(d, a, r):
    tt = t(d)
    return np.minimum(1, tt / max(a, 1e-4)) * np.exp(-np.maximum(0, tt - a) / max(r, 1e-4))


def lowpass(x, cutoff):  # one-pole, cutoff may be an array (sweeps)
    c = np.broadcast_to(np.asarray(cutoff, float), x.shape)
    a = np.exp(-2 * np.pi * c / SR)
    y = np.zeros_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc = (1 - a[i]) * x[i] + a[i] * acc
        y[i] = acc
    return y


def whoosh(d, f0, f1, peak):
    n = rng.standard_normal(int(d * SR))
    tt = t(d)
    sweep = f0 * (f1 / f0) ** (tt / d)
    y = lowpass(n, sweep) - lowpass(n, sweep * 0.3)
    shape = np.exp(-((tt - peak) ** 2) / (2 * (d / 6) ** 2))
    return y * shape / (np.abs(y * shape).max() + 1e-9) * 0.7


def pop(f, d=0.12, drop=0.5):
    tt = t(d)
    freq = f * (1 - drop * tt / d)
    return np.sin(2 * np.pi * np.cumsum(freq) / SR) * env(d, 0.003, d / 4) * 0.7


def main(out: Path):
    s = out / "sfx"
    write(s / "whoosh-soft.wav", whoosh(0.9, 300, 3000, 0.5))
    write(s / "whoosh-fast.wav", whoosh(0.45, 600, 6000, 0.22))
    write(s / "pop-soft.wav", pop(520))
    write(s / "pop-bright.wav", pop(900, 0.09, 0.3))
    click = rng.standard_normal(int(0.03 * SR)) * env(0.03, 0.0005, 0.004)
    write(s / "click-ui.wav", lowpass(click, 5000) * 2.5)
    tt = t(0.7)
    thump = np.sin(2 * np.pi * np.cumsum(90 * np.exp(-tt * 6) + 45) / SR) * env(0.7, 0.002, 0.18)
    write(s / "impact-low.wav", thump * 0.9 + lowpass(rng.standard_normal(len(tt)), 900) * env(0.7, 0.001, 0.05) * 0.3)
    tt = t(1.2)
    bell = sum(np.sin(2 * np.pi * f * tt) * g for f, g in ((1318.5, 0.5), (1975.5, 0.3), (2637, 0.15)))
    write(s / "ding-success.wav", bell * env(1.2, 0.004, 0.35) * 0.6)
    write(s / "riser.wav", whoosh(1.6, 200, 5000, 1.5) * np.linspace(0.3, 1, int(1.6 * SR)))

    # music: 90 BPM, 4 bars of soft pad chords + plucks, loops seamlessly (bar = 2.667 s; 6 bars = 16 s)
    bpm, bars = 90, 6
    beat = 60 / bpm
    total = bars * 4 * beat
    tt = t(total)
    y = np.zeros_like(tt)
    chords = [(220.0, 277.18, 329.63), (196.0, 246.94, 293.66), (174.61, 220.0, 261.63), (196.0, 246.94, 329.63)]
    for b in range(bars):
        ch = chords[b % 4]
        a, z = int(b * 4 * beat * SR), int((b + 1) * 4 * beat * SR)
        seg = tt[a:z] - tt[a]
        pad = sum(np.sin(2 * np.pi * f * seg) + 0.3 * np.sin(2 * np.pi * 2 * f * seg) for f in ch)
        fade = np.minimum(1, np.minimum(seg / 0.3, (seg[-1] - seg + 1e-3) / 0.3))
        y[a:z] += pad * fade * 0.08
        for k in range(8):  # eighth-note plucks
            p0 = a + int(k * beat / 2 * SR)
            f = ch[k % 3] * 2
            d = min(0.4, (z - p0) / SR)
            y[p0:p0 + int(d * SR)] += np.sin(2 * np.pi * f * t(d)) * env(d, 0.002, 0.12) * 0.12
    write(out / "music" / "calm-loop.wav", y / np.abs(y).max() * 0.6)
    (out / "LICENSE.txt").write_text("These sounds and music were synthesised by tools/make_demo_audio.py for\n"
                                     "open-explainer and are released under the MIT License.\n")
    print(f"wrote demo audio to {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "examples/audio"))
